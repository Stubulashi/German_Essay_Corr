/**
 * 使用指南内容数据(结构化,支持搜索与折叠渲染)
 *
 * 数据结构说明:
 * - GuideSection:模块分组(与左侧导航功能模块一一对应,外加快速开始/排障);
 * - GuideItem:单个功能点,四要素描述 —— 作用 / 适用场景 / 操作步骤 / 关键参数与注意事项;
 * - 内容全部为前端静态数据(无后端依赖),便于随版本维护与检索。
 */

export interface GuideParam {
  /** 参数/选项名称 */
  name: string
  /** 含义与建议取值 */
  meaning: string
}

export interface GuideItem {
  /** 功能名称 */
  title: string
  /** 作用:这个功能解决什么问题 */
  purpose: string
  /** 适用场景 */
  scenes: string
  /** 操作步骤(按顺序) */
  steps: string[]
  /** 关键参数含义(可选) */
  params?: GuideParam[]
  /** 注意事项(可选) */
  notes?: string[]
}

export interface GuideSection {
  /** 锚点 ID(目录跳转用) */
  id: string
  /** 分组标题 */
  title: string
  /** 一句话概述 */
  summary: string
  items: GuideItem[]
}

